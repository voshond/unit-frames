#!/usr/bin/env bash
# Fetch/update the embedded libraries into UnitFrames/Libs (they are committed, pinned copies).
#
# Usage:
#   scripts/fetch-libs.sh
#
# Environment overrides:
#   ACE3_REF   git ref of WoWUIDev/Ace3 to use (default: master, has the Forever AceDB fixes)
#   OUF_REF    git ref of oUF-wow/oUF (default: release tag 14.2.0, supports Forever)
#   LEM_REF    git ref of p3lim-wow/LibEditMode (default: tag 18, supports Forever)
#   LDB_REF    git ref of tekkub/libdatabroker-1-1 (default: master @ 1a63ede, minor 4)
#   DBICON_REV WowAce SVN revision of LibDBIcon-1.0 (default: 168, minor 57, lists Interface 16001)
#   LSM_SRC    path to a LibSharedMedia-3.0 folder to copy from. LSM lives in WowAce SVN which
#              needs auth, so by default we take the newest copy embedded in an installed addon.
#   WOW_DIR    WoW client dir used to look for LSM (same default as install.sh)

set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LIBS_DIR="$REPO_DIR/UnitFrames/Libs"
ACE3_REF="${ACE3_REF:-master}"
OUF_REF="${OUF_REF:-14.2.0}"
LEM_REF="${LEM_REF:-18}"
LDB_REF="${LDB_REF:-1a63ede0248c11aa1ee415187c1f9c9489ce3e02}"
DBICON_REV="${DBICON_REV:-168}"
WOW_DIR="${WOW_DIR:-/mnt/data02/Games/Faugus/battlenet/drive_c/Program Files (x86)/World of Warcraft/_forever_}"

die() { echo "error: $*" >&2; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

replace_lib() {
	local src="$1" name="$2"
	[[ -d "$src" ]] || die "missing $src"
	# Stage a copy (sources may be another addon's folder) and drop repo/dev
	# files from it; only the runtime code ships.
	local stage="$tmp/stage/$name"
	rm -rf "$stage"
	mkdir -p "$tmp/stage"
	cp -r "$src" "$stage"
	rm -rf "$stage"/.[!.]* "$stage/utils" "$stage/tests"
	rm -rf -- "${LIBS_DIR:?}/$name"
	cp -r "$stage" "$LIBS_DIR/$name"
	echo "updated  $name"
}

mkdir -p "$LIBS_DIR"

# --- Ace3 parts -------------------------------------------------------------
git -c advice.detachedHead=false clone -q --depth 1 --branch "$ACE3_REF" https://github.com/WoWUIDev/Ace3.git "$tmp/Ace3"
ace3_rev="$(git -C "$tmp/Ace3" rev-parse --short HEAD)"
for lib in LibStub CallbackHandler-1.0 AceDB-3.0; do
	replace_lib "$tmp/Ace3/$lib" "$lib"
done

# --- oUF (embedded; no X-oUF in our TOC, so it creates no global) -----------
git -c advice.detachedHead=false clone -q --depth 1 --branch "$OUF_REF" https://github.com/oUF-wow/oUF.git "$tmp/oUF"
ouf_rev="$(git -C "$tmp/oUF" rev-parse --short HEAD)"
rm -f "$tmp/oUF/oUF.toc"
sed -i "s/@project-version@/$OUF_REF/" "$tmp/oUF/ouf.lua"
replace_lib "$tmp/oUF" oUF

# --- LibEditMode --------------------------------------------------------------
git -c advice.detachedHead=false clone -q --depth 1 --branch "$LEM_REF" https://github.com/p3lim-wow/LibEditMode.git "$tmp/LibEditMode"
lem_rev="$(git -C "$tmp/LibEditMode" rev-parse --short HEAD)"
rm -f "$tmp/LibEditMode/LibEditMode.toc"
replace_lib "$tmp/LibEditMode" LibEditMode

mkdir -p "$tmp/LibDataBroker-1.1"
curl --fail --silent --show-error --location --retry 3 \
	"https://raw.githubusercontent.com/tekkub/libdatabroker-1-1/$LDB_REF/LibDataBroker-1.1.lua" \
	-o "$tmp/LibDataBroker-1.1/LibDataBroker-1.1.lua"
replace_lib "$tmp/LibDataBroker-1.1" LibDataBroker-1.1
ldb_rev="${LDB_REF:0:7}"

mkdir -p "$tmp/LibDBIcon-1.0"
for file in LibDBIcon-1.0.lua lib.xml; do
	curl --fail --silent --show-error --location --retry 3 \
		"https://repos.curseforge.com/wow/libdbicon-1-0/trunk/LibDBIcon-1.0/$file?p=$DBICON_REV" \
		-o "$tmp/LibDBIcon-1.0/$file"
done
replace_lib "$tmp/LibDBIcon-1.0" LibDBIcon-1.0
dbicon_minor="$(grep -m1 -oE 'DBICON10_MINOR = [0-9]+' "$LIBS_DIR/LibDBIcon-1.0/LibDBIcon-1.0.lua" | grep -oE '[0-9]+$')"

# --- LibSharedMedia-3.0 -----------------------------------------------------
lsm_minor() { grep -m1 -oE '"LibSharedMedia-3.0", [0-9]+' "$1/LibSharedMedia-3.0.lua" | grep -oE '[0-9]+$'; }

if [[ -z "${LSM_SRC:-}" ]]; then
	best=0
	while IFS= read -r -d '' f; do
		dir="$(dirname "$f")"
		[[ "$dir" == "$LIBS_DIR"/* ]] && continue
		minor="$(lsm_minor "$dir" || echo 0)"
		if (( minor > best )); then best="$minor"; LSM_SRC="$dir"; fi
	done < <(find "$WOW_DIR/Interface/AddOns" -name 'LibSharedMedia-3.0.lua' -print0 2>/dev/null)
fi
[[ -n "${LSM_SRC:-}" ]] || die "no LibSharedMedia-3.0 found; set LSM_SRC"
replace_lib "$LSM_SRC" LibSharedMedia-3.0
lsm_rev="$(lsm_minor "$LIBS_DIR/LibSharedMedia-3.0")"

# --- UnitFrames_Media embeds what it needs to register fonts on its own --------
MEDIA_LIBS_DIR="$REPO_DIR/UnitFrames_Media/Libs"
mkdir -p "$MEDIA_LIBS_DIR"
for lib in LibStub CallbackHandler-1.0 LibSharedMedia-3.0; do
	rm -rf -- "${MEDIA_LIBS_DIR:?}/$lib"
	cp -r "$LIBS_DIR/$lib" "$MEDIA_LIBS_DIR/$lib"
done
echo "updated  UnitFrames_Media/Libs"

cat > "$LIBS_DIR/VERSIONS.md" <<EOF
# Embedded libraries

Generated by \`scripts/fetch-libs.sh\` on $(date +%F). Do not edit these folders by hand.

| Library | Source | Version |
|---|---|---|
| LibStub, CallbackHandler-1.0, AceDB-3.0 | https://github.com/WoWUIDev/Ace3 | \`$ACE3_REF\` @ \`$ace3_rev\` |
| oUF | https://github.com/oUF-wow/oUF | \`$OUF_REF\` @ \`$ouf_rev\` |
| LibEditMode | https://github.com/p3lim-wow/LibEditMode | \`$LEM_REF\` @ \`$lem_rev\` |
| LibSharedMedia-3.0 | WowAce (copied from an installed addon) | minor \`$lsm_rev\` |
| LibDataBroker-1.1 | https://github.com/tekkub/libdatabroker-1-1 | \`$ldb_rev\` (minor 4) |
| LibDBIcon-1.0 | WowAce SVN libdbicon-1-0 | r\`$DBICON_REV\` (minor \`$dbicon_minor\`) |
EOF
echo "done. See $LIBS_DIR/VERSIONS.md"
