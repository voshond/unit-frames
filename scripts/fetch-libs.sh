#!/usr/bin/env bash
# Fetch/update the embedded libraries into UnitFrames/Libs (they are committed, pinned copies).
#
# Usage:
#   scripts/fetch-libs.sh
#
# Environment overrides:
#   ACE3_REF   git ref of WoWUIDev/Ace3 to use (default: master, has the Forever AceDB fixes)
#   LSM_SRC    path to a LibSharedMedia-3.0 folder to copy from. LSM lives in WowAce SVN which
#              needs auth, so by default we take the newest copy embedded in an installed addon.
#   WOW_DIR    WoW client dir used to look for LSM (same default as install.sh)

set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LIBS_DIR="$REPO_DIR/UnitFrames/Libs"
ACE3_REF="${ACE3_REF:-master}"
WOW_DIR="${WOW_DIR:-/mnt/data02/Games/Faugus/battlenet/drive_c/Program Files (x86)/World of Warcraft/_classic_beta_}"

die() { echo "error: $*" >&2; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

replace_lib() {
	local src="$1" name="$2"
	[[ -d "$src" ]] || die "missing $src"
	rm -rf -- "${LIBS_DIR:?}/$name"
	cp -r "$src" "$LIBS_DIR/$name"
	echo "updated  $name"
}

mkdir -p "$LIBS_DIR"

# --- Ace3 parts -------------------------------------------------------------
git clone -q --depth 1 --branch "$ACE3_REF" https://github.com/WoWUIDev/Ace3.git "$tmp/Ace3"
ace3_rev="$(git -C "$tmp/Ace3" rev-parse --short HEAD)"
for lib in LibStub CallbackHandler-1.0 AceDB-3.0; do
	replace_lib "$tmp/Ace3/$lib" "$lib"
done

# --- LibSharedMedia-3.0 -----------------------------------------------------
lsm_minor() { grep -m1 -oE '"LibSharedMedia-3.0", [0-9]+' "$1/LibSharedMedia-3.0.lua" | grep -oE '[0-9]+$'; }

if [[ -z "${LSM_SRC:-}" ]]; then
	best=0
	while IFS= read -r -d '' f; do
		dir="$(dirname "$f")"
		[[ "$dir" == "$LIBS_DIR"/* ]] && continue
		minor="$(lsm_minor "$dir" || echo 0)"
		if (( minor > best )); then best="$minor"; LSM_SRC="$dir"; fi
	done < <(find "$WOW_DIR/Interface/AddOns" -name 'LibSharedMedia-3.0.lua' -print0 2>/dev/null)
fi
[[ -n "${LSM_SRC:-}" ]] || die "no LibSharedMedia-3.0 found; set LSM_SRC"
replace_lib "$LSM_SRC" LibSharedMedia-3.0
lsm_rev="$(lsm_minor "$LIBS_DIR/LibSharedMedia-3.0")"

cat > "$LIBS_DIR/VERSIONS.md" <<EOF
# Embedded libraries

Generated by \`scripts/fetch-libs.sh\` on $(date +%F). Do not edit these folders by hand.

| Library | Source | Version |
|---|---|---|
| LibStub, CallbackHandler-1.0, AceDB-3.0 | https://github.com/WoWUIDev/Ace3 | \`$ACE3_REF\` @ \`$ace3_rev\` |
| LibSharedMedia-3.0 | WowAce (copied from an installed addon) | minor \`$lsm_rev\` |
EOF
echo "done. See $LIBS_DIR/VERSIONS.md"
