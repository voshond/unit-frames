--[[
The client API contract for the mock, from tests/fixtures/api_snapshot.lua
(generated by scripts/api-snapshot.lua from Blizzard's API documentation and
Lua source). The mock's behaviour is hand-written; this keeps its surface
honest:

  - widget methods must be documented for the object's type, or defined by a
    Blizzard Lua mixin (templates such as BackdropTemplate)
  - documented functions check their arguments like the client: required
    plain arguments, and the secret argument policy (addon code is tainted,
    so only "AllowedWhenTainted" accepts secrets)
  - documented protected functions are blocked on protected objects in combat

It cannot prove behaviour (what a function returns, layout, rendering); the
contract spec checks the mock's declared secrets, enums and events.
]]
local API = {}
local SNAPSHOT = "tests/fixtures/api_snapshot.lua"

local function Chain(base, ...)
	local chain = { unpack(base) }
	for i = 1, select("#", ...) do chain[#chain + 1] = select(i, ...) end
	return chain
end

-- Documented script object APIs per object type, base first.
local FSO, OBJECT = "SimpleFrameScriptObjectAPI", "SimpleObjectAPI"
local SCRIPT_REGION = { FSO, OBJECT, "SimpleScriptRegionAPI", "SimpleScriptRegionResizingAPI",
	"SimpleAnimatableObjectAPI" }
local REGION = Chain(SCRIPT_REGION, "SimpleRegionAPI")
local FRAME = Chain(SCRIPT_REGION, "SimpleFrameAPI")
local BUTTON = Chain(FRAME, "SimpleButtonAPI")
local ANIMATION = { FSO, OBJECT, "SimpleAnimAPI" }
API.TYPES = {
	Texture = Chain(REGION, "SimpleTextureBaseAPI", "SimpleTextureAPI"),
	Line = Chain(REGION, "SimpleTextureBaseAPI", "SimpleLineAPI"),
	FontString = Chain(REGION, "SimpleFontStringAPI"),
	Font = { FSO, "SimpleFontAPI" },
	Frame = FRAME,
	EventFrame = FRAME,
	AuraContainer = FRAME,
	Button = BUTTON,
	DropdownButton = BUTTON,
	CheckButton = Chain(BUTTON, "SimpleCheckboxAPI"),
	StatusBar = Chain(FRAME, "SimpleStatusBarAPI"),
	Slider = Chain(FRAME, "SimpleSliderAPI"),
	EditBox = Chain(FRAME, "SimpleEditBoxAPI"),
	Cooldown = Chain(FRAME, "FrameAPICooldown"),
	PlayerModel = Chain(FRAME, "SimpleModelAPI", "FrameAPICharacterModelBase"),
	GameTooltip = Chain(FRAME, "FrameAPITooltip"),
	AnimationGroup = { FSO, OBJECT, "SimpleAnimGroupAPI" },
	Animation = ANIMATION,
	Alpha = Chain(ANIMATION, "SimpleAnimAlphaAPI"),
	FlipBook = Chain(ANIMATION, "SimpleAnimFlipBookAPI"),
	Duration = { "LuaDurationObjectAPI" },
	SecondsFormatter = { "SecondsFormatterAPI" },
	DurationTextBinding = { "DurationTextBindingObjectAPI" },
	Curve = { "LuaCurveObjectBaseAPI", "LuaCurveObjectAPI" },
	ColorCurve = { "LuaCurveObjectBaseAPI", "LuaColorCurveObjectAPI" },
	UnitHealPredictionCalculator = { "UnitHealPredictionCalculatorAPI" },
}

function API.Snapshot()
	if not API.snapshot then
		local file = io.open(SNAPSHOT)
		assert(file, SNAPSHOT .. " is missing: run luajit scripts/api-snapshot.lua")
		file:close()
		API.snapshot = dofile(SNAPSHOT)
	end
	return API.snapshot
end

-- The documented method `name` for `objectType`, and whether the type is
-- modelled at all (unmodelled mock objects are not checked).
local resolved = {}
function API.Method(objectType, name)
	local chain = API.TYPES[objectType]
	if not chain then return nil, false end
	local byName = resolved[objectType]
	if not byName then byName = {}; resolved[objectType] = byName end
	local def = byName[name]
	if def == nil then
		def = false
		local objects = API.Snapshot().scriptObjects
		for i = #chain, 1, -1 do
			def = objects[chain[i]] and objects[chain[i]][name] or false
			if def then break end
		end
		byName[name] = def
	end
	return def or nil, true
end

-- A Blizzard Lua mixin defining `name` (template methods), or nil.
function API.LuaMethod(name)
	return API.Snapshot().lua.methods[name]
end

-- "UnitHealth" or "C_Spell.IsSpellInRange".
function API.Function(name)
	return API.Snapshot().functions[name]
end

-- A global or table field defined in Blizzard's Lua, or nil.
function API.LuaGlobal(name)
	return API.Snapshot().lua.globals[name]
end

-- Undocumented engine functions (name) and methods (":name") that Blizzard
-- code calls: evidence they exist, without a signature to check.
function API.Called(name)
	return API.Snapshot().lua.called[name]
end

-- Documented types the client converts strictly enough to check here.
local NUMBER = { number = true, luaIndex = true, fileID = true, time_t = true, uiUnit = true, size = true,
	SingleColorValue = true, normalizedValue = true, WOWMONEY = true }
local STRING = { cstring = true, string = true, UnitToken = true, textureAtlas = true, WOWGUID = true }

-- Parsed once per definition: { name, kind, nilable, check } per argument.
local function Fields(def)
	if not def.fields then
		def.fields = {}
		for i, field in ipairs(def.args or {}) do
			local name, kind, nilable = field:match("^([^:]*):([^?]*)(%??)$")
			local check = NUMBER[kind] and "number" or (STRING[kind] or kind:match("^UnitToken")) and "string" or nil
			def.fields[i] = { name = name, kind = kind, nilable = nilable == "?", check = check }
		end
	end
	return def.fields
end

-- Lua VM built-ins (issecretvalue, scrubsecretvalues, ...) all document the
-- default "AllowedWhenUntainted", although addons call them with secrets by
-- design. Their secret policy is not modelled.
local UNMODELLED_SECRET_POLICY = { FrameScript = true }

local function Label(owner, name)
	return owner and owner .. ":" .. name or name
end

-- Raises a client-like error for a call that the client would reject.
-- Untainted (Blizzard secure) callers may pass secrets wherever allowed.
-- `owner` is the object type for methods (nil for functions); the
-- "Type:Method" label is only built for an error, as this runs on every call.
function API.CheckArgs(owner, name, def, isSecret, untainted, ...)
	local policy = not untainted and not UNMODELLED_SECRET_POLICY[def.system] and def.secretArguments
	if policy and policy ~= "AllowedWhenTainted" then
		for i = 1, select("#", ...) do
			if isSecret((select(i, ...))) then
				error(string.format("%s: secret argument %d is not allowed from addon code (%s)", Label(owner, name), i, policy), 3)
			end
		end
	end
	for i, field in ipairs(Fields(def)) do
		local value = select(i, ...)
		if field.check and value == nil then
			if not field.nilable then
				error(string.format("%s: argument %d (%s) is required", Label(owner, name), i, field.name), 3)
			end
		elseif field.check and not isSecret(value) then
			local ok
			if field.check == "number" then ok = type(value) == "number" or (type(value) == "string" and tonumber(value) ~= nil)
			else ok = type(value) == "string" or type(value) == "number" end
			if not ok then
				error(string.format("%s: argument %d (%s) must be %s, got %s", Label(owner, name), i, field.name, field.kind, type(value)), 3)
			end
		end
	end
end

return API
