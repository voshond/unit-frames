local Helpers = require("helpers")

describe("Ready check icon attachment", function()
	it("replays the current sample when an icon is attached or its settings change", function()
		local UF = Helpers.LoadAddon(true, true)
		local uf = UF.Units:CreateFrame("target", UIParent)
		uf:ShowReadyCheckSample("ready", 5.75)
		local icon = UF.Components.ReadyCheckIcon:New(uf:GetFrame(), {})
		uf:AttachReadyCheckIcon(icon)
		assert.is_true(icon:GetWidget():IsShown())
		assert.equals(0.5, icon:GetWidget():GetAlpha())
		icon:Apply({ enabled = false })
		uf:AttachReadyCheckIcon(icon)
		assert.is_false(icon:GetWidget():IsShown())
		icon:Apply({ enabled = true })
		uf:AttachReadyCheckIcon(icon)
		assert.is_true(icon:GetWidget():IsShown())
		uf:SetReadyCheck(nil)
		uf:AttachReadyCheckIcon(icon)
		assert.is_false(icon:GetWidget():IsShown())
		uf:Release()
		icon:Release()
	end)

	it("preserves a live result and prevents an old attachment detaching its replacement", function()
		local UF = Helpers.LoadAddon(true, true)
		local uf = UF.Units:CreateFrame("target", UIParent)
		local first = UF.Components.ReadyCheckIcon:New(uf:GetFrame(), {})
		local second = UF.Components.ReadyCheckIcon:New(uf:GetFrame(), {})
		uf:SetReadyCheck("ready")
		uf:FinishReadyCheck()
		uf.readyCheckDriver:RunScript("OnUpdate", 2.75)
		uf:AttachReadyCheckIcon(first)
		assert.equals(0.5, first:GetWidget():GetAlpha())
		uf:AttachReadyCheckIcon(second)
		assert.is_false(first:GetWidget():IsShown())
		uf:DetachReadyCheckIcon(first)
		assert.equals(second, uf:GetReadyCheckIcon())
		assert.equals(0.5, second:GetWidget():GetAlpha())
		uf:DetachReadyCheckIcon(second)
		assert.is_nil(uf:GetReadyCheckIcon())
		assert.is_false(second:GetWidget():IsShown())
		assert.is_false(first.released == true, "attachment never owns the icon")
		uf:Release()
		assert.is_nil(uf.readyCheckDriver:GetScript("OnUpdate"))
		first:Release()
		second:Release()
	end)

	it("leaves live binding changes to the unit adapter", function()
		local UF, CG = Helpers.LoadClickGrid()
		local member = CG.headers.party:GetAttribute("child1").Member
		CG.Config:SetStyle("member", "readyCheck.enabled", false)
		CG.Config:Set("indicators.ready", false)
		assert.is_false(member:IsElementEnabled("UF_ReadyCheck"))
		CG.Config:Set("indicators.ready", true)
		assert.is_true(member:IsElementEnabled("UF_ReadyCheck"))
		assert.equals(member.ufcgStatus.readyCheckIcon, member.uf:GetReadyCheckIcon())
	end)
end)
