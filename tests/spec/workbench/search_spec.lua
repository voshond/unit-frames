local Helpers = require("helpers")
local Mock = Helpers.Mock

local function Row(wb, path)
	for _, row in ipairs(wb.inspector.page.rows) do if row.path == path and row.control then return row end end
end

describe("Workbench search navigation", function()
	it("restores valid destinations and preview preferences without discarding entry configs", function()
		local _, wb = Helpers.LoadWorkbench()
		local state = wb:GetState(wb.entries["unit.player"])
		state.section, state.config = "health.bar.segments.absorb", { retained = true }
		wb:Open("unit.player")
		assert.equals("@health", wb.state.section)
		assert.equals("style:shields", wb.state.localSections["@health"])
		assert.is_true(state.config.retained)
		wb.content:SetWidth(1030)
		wb:LayoutWorkbench()
		assert.is_false(wb.previewPane:IsShown())
		wb.previewToggle.opts.onClick()
		assert.is_true(wb.previewPane:IsShown())
		assert.is_true(wb:GetDB().stage.preview)
		wb.previewToggle.opts.onClick()
		wb:Select("unit.target")
		assert.is_false(wb.previewPane:IsShown())
	end)

	it("shows group defaults before shared appearance and links to the exact inherited default", function()
		local UF, wb = Helpers.LoadWorkbench()
		wb:Open("unit.player")
		local model = wb:GetCatalogue().models["unit.player"]
		wb:OpenDestination(model.owners["style|health.belowLeft.size"])
		assert.equals("Frame default", Row(wb, "health.belowLeft.size").source:GetText())
		wb:OpenDestination(model.owners["style|health.left.font"])
		local row = Row(wb, "health.left.font")
		assert.equals("Shared appearance", row.source:GetText())
		row.control.opts.onChange("Morpheus")
		assert.equals("Custom value", row.source:GetText())
		row.reset:RunScript("OnClick")
		assert.equals("Shared appearance", row.source:GetText())
		row.sourceLink.opts.onClick()
		assert.equals("theme", wb.entry.id)
		assert.equals("font", wb.inspector.revealedPath)
		assert.equals("Shared appearance defaults", wb.entry.scope)
		assert.is_nil(UF.Util.GetPath(UF.Config:GetUnitConfig("player"), "health.left.font"))
	end)

	it("opens unvisited settings and reuses the current preview for local destinations", function()
		local UF, wb = Helpers.LoadWorkbench()
		wb:Open("unit.player")
		local session = wb.session
		wb:OpenDestination(wb:FindSettings("player shield placement")[1].record)
		assert.equals(session, wb.session)
		assert.equals("@health", wb.state.section)
		assert.equals("style:shields", wb.state.localSections["@health"])
		assert.equals("health.bar.segments.absorb.placement", wb.inspector.revealedPath)
		local current = UF.Util.Copy(UF.Config:GetUnitConfig("target"))
		wb:OpenDestination(wb:FindSettings("target health percent")[1].record)
		assert.equals("unit.target", wb.entry.id)
		assert.is_true(session.released)
		assert.same(current, UF.Config:GetUnitConfig("target"))
		assert.is_true(wb.inspector.highlight:IsShown())
		wb.inspector.highlight:RunScript("OnUpdate", 4)
		assert.is_nil(wb.inspector.revealedPath)
	end)

	it("explains range prerequisites and links to the controlling field without changing it", function()
		local UF, wb = Helpers.LoadWorkbench()
		wb:Open("unit.player")
		local result = wb:FindSettings("range spell", { entryId = "unit.player" })[1].record
		wb:OpenDestination(result)
		assert.is_false(Row(wb, "range.spell").region:IsShown())
		assert.is_not_nil(wb.navigationMessage:GetText():find("Choose Spell range", 1, true))
		assert.is_true(wb.prerequisiteButton:GetFrame():IsShown())
		wb.prerequisiteButton.opts.onClick()
		assert.equals("range.mode", wb.inspector.revealedPath)
		assert.equals("group", UF.Config:UnitStore("player"):Resolved().range.mode)
	end)

	it("expands section details, preserves scroll and closes stale colour callbacks", function()
		local UF, wb = Helpers.LoadWorkbench()
		wb:Open("unit.player")
		wb:SelectSection("portrait")
		local record = wb:GetCatalogue().models["unit.player"].owners["style|portrait.offsetX"]
		if not record then record = wb:GetCatalogue().models["unit.player"].owners["style|raidTarget.offsetX"] end
		wb:OpenDestination(record)
		assert.is_true(Row(wb, record.path).region:IsShown())
		assert.is_true(wb.inspector.page.detailsExpanded)
		local model = wb:GetCatalogue().models["unit.player"]
		wb:OpenDestination(model.owners["style|health.bar.segments.absorb.color"])
		local swatch = Row(wb, "health.bar.segments.absorb.color").control
		swatch:OpenPicker()
		local token = swatch.pickerToken
		wb:SelectSection("power")
		assert.is_not_nil(token)
		assert.is_nil(swatch.pickerToken)
		assert.is_nil(wb.inspector.revealedPath)
		assert.is_not_nil(UF.Config:UnitStore("player"))
	end)

	it("handles live typing, keyboard results, escape and clearing without persisting queries", function()
		local _, wb = Helpers.LoadWorkbench()
		wb:Open("unit.player")
		local session = wb.session
		wb.search.input:SetText("shield placement")
		wb.search.input:RunScript("OnTextChanged", true)
		assert.is_true(wb.resultPanel:IsShown())
		assert.equals(session, wb.session)
		wb.search.input:RunScript("OnArrowPressed", "DOWN")
		assert.equals(2, wb.searchSelection)
		local results, items = wb.searchResults, wb.resultList.items
		wb.resultList.box:SetScrollPercentage(0.5)
		wb.search.input:RunScript("OnEnterPressed")
		assert.is_false(wb.resultPanel:IsShown())
		assert.equals("shield placement", wb.searchQuery)
		wb.search.input:RunScript("OnEditFocusGained")
		assert.is_true(wb.resultPanel:IsShown())
		assert.equals(2, wb.searchSelection)
		assert.equals(results, wb.searchResults)
		assert.equals(items, wb.resultList.items)
		assert.equals(0.5, wb.resultList.box:GetScrollPercentage())
		wb.search.input:RunScript("OnEscapePressed")
		assert.is_false(wb.resultPanel:IsShown())
		wb.clearSearch.opts.onClick()
		assert.equals("", wb.searchQuery)
		assert.is_nil(wb:GetDB().searchQuery)
	end)

	it("groups results under highlighted location headers that stick while scrolling", function()
		local _, wb = Helpers.LoadWorkbench()
		wb:Open("unit.player")
		wb.searchFilter:Select("frame")
		wb.search.input:SetText("glow size")
		wb.search.input:RunScript("OnTextChanged", true)
		local function Plain(text) return (text:gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", "")) end
		local layout = {}
		for _, item in ipairs(wb.resultList.items) do
			layout[#layout + 1] = (item.sticky and "# " or item.header and "= " or "") .. Plain(item.text)
		end
		assert.same({ "# Unit Frames > Player > Buffs & Debuffs > External Icons > Debuff Glow", "Glow size",
			"# Unit Frames > Player > Buffs & Debuffs > Embedded Row > Debuff Glow", "Glow size" }, layout)
		assert.equals("|cff4fa3ffGlow|r |cff4fa3ffsize|r", wb.resultList.items[2].text)
		assert.is_not_nil(wb.resultList.items[1].text:find("|cff4fa3ffGlow|r", 1, true))
		local sticky = wb.resultList.sticky
		assert.is_true(sticky:IsShown())
		assert.equals(wb.resultList.items[1].text, sticky.text:GetText())
		wb.resultList.box:ScrollToOffset(28)
		assert.equals(wb.resultList.items[1].text, sticky.text:GetText())
		local _, _, _, _, push = sticky:GetPoint(1)
		assert.equals(6, push)
		wb.resultList.box:ScrollToOffset(48)
		assert.equals(wb.resultList.items[3].text, sticky.text:GetText())
		local model = wb:GetCatalogue().models["unit.player"]
		assert.equals("Unit Frames > Player > Cast Bar > Bar > Spell Name", model.owners["style|castbar.name.size"].breadcrumb)
		assert.equals("Unit Frames > Player > Health & Shields > DoT Damage",
			model.owners["style|health.bar.pendingDamage.lethalIconSize"].breadcrumb)
		assert.equals("Unit Frames > Player > Health & Shields > Left Text", model.owners["style|health.left.size"].breadcrumb)
	end)

	it("groups preview results without including headings in keyboard selection or result counts", function()
		local _, wb = Helpers.LoadWorkbench()
		wb:Open("unit.player")
		wb.searchFilter:Select("preview")
		wb.search.input:SetText("health")
		wb.search.input:RunScript("OnTextChanged", true)
		local headings, records = {}, 0
		for _, item in ipairs(wb.resultList.items) do
			if item.header and not item.sticky then headings[#headings + 1] = item.text
			elseif not item.header then records = records + 1; assert.equals(records, item.id) end
		end
		assert.same({ "Settings", "Preview Only — Simulation" }, headings)
		assert.equals(records .. " results", wb.resultCount:GetText())
		wb.resultList:Select(records, true)
		assert.equals(records, wb.searchSelection)
		assert.equals("@data", wb.state.section)
		wb.search.input:RunScript("OnEditFocusGained")
		assert.equals(records, wb.searchSelection)
		wb.search.input:SetText("shield placement")
		wb.search.input:RunScript("OnTextChanged", true)
		assert.equals(1, wb.searchSelection)
		wb.searchFilter:Select("frame")
		assert.equals(1, wb.searchSelection)
		for _, result in ipairs(wb.searchResults) do assert.equals(wb.entry.id, result.record.entryId) end
		wb.search.input:SetText("abracadabra")
		wb.search.input:RunScript("OnTextChanged", true)
		assert.equals(0, #wb.resultList.items)
		assert.equals("No results — try fewer words or All settings.", wb.resultCount:GetText())
		assert.has_no_error(function() wb.search.input:RunScript("OnEnterPressed") end)
	end)

	it("navigates to import and positioning help without running an action", function()
		local UF, wb = Helpers.LoadWorkbench()
		wb:Open("unit.player")
		local before = UF.Profiles:GetCurrent()
		wb:OpenDestination(wb:FindSettings("import profile")[1].record)
		assert.equals("profiles", wb.entry.id)
		assert.equals(before, UF.Profiles:GetCurrent())
		wb:OpenDestination(wb:FindSettings("move target frame")[1].record)
		assert.equals("unit.target", wb.entry.id)
		assert.is_not_nil(wb.navigationMessage:GetText():find("Edit Mode", 1, true))
	end)

	it("invalidates the catalogue when ClickGrid registers while Workbench is open", function()
		local _, wb = Helpers.LoadWorkbench()
		wb:Open("unit.player")
		local previous = wb:GetCatalogue()
		Helpers.LoadToc("UnitFrames_ClickGrid/UnitFrames_ClickGrid.toc", "UnitFrames_ClickGrid")
		Mock.FireEvent("ADDON_LOADED", "UnitFrames_ClickGrid")
		Mock.FireEvent("PLAYER_LOGIN")
		assert.is_false(previous == wb:GetCatalogue())
		assert.is_true(wb:ValidateCatalogue())
		assert.equals("clickgrid.bindings", wb:FindSettings("left click heal")[1].record.entryId)
	end)
end)
