local Helpers = require("helpers")

describe("Standalone castbar frame #castbar", function()
	local ns, frame
	before_each(function()
		ns = Helpers.LoadAddon(true)
		frame = ns.Components.CastbarFrame:New(UIParent, {})
	end)

	it("reserves an idle cast row and offers disabled swing rows", function()
		assert.equals(280, frame:GetFrame():GetWidth())
		assert.equals(24, frame:GetFrame():GetHeight())
		assert.is_true(frame:GetFrame():IsShown())
		assert.is_false(frame:GetCastbar():GetFrame():IsShown())
		assert.is_not_nil(frame:GetCastbar().gcd)
		for _, key in ipairs({ "mainHand", "offHand", "ranged" }) do
			assert.is_false(frame:GetRow(key):IsEnabled())
			assert.equals(0, frame:GetRow(key):GetBar():GetStatusBar():GetValue())
		end
		assert.is_nil(frame:GetRow("health"))
	end)

	it("stacks enabled rows at their configured heights and collapses disabled rows", function()
		frame:Apply({ width = 320, gap = 3, mainHand = { enabled = true, height = 12 },
			offHand = { enabled = true }, ranged = { enabled = true, height = 8 } })
		assert.equals(63, frame:GetFrame():GetHeight())
		assert.same({ "TOPLEFT", frame:GetFrame(), "TOPLEFT", 0, -27 }, frame:GetRow("mainHand"):GetFrame():GetAnchor("TOPLEFT"))
		assert.same({ "TOPLEFT", frame:GetFrame(), "TOPLEFT", 0, -55 }, frame:GetRow("ranged"):GetFrame():GetAnchor("TOPLEFT"))
		assert.equals(320, frame:GetRow("ranged"):GetFrame():GetWidth())
		frame:Apply({ castbar = { enabled = false }, ranged = { enabled = true } })
		assert.equals(10, frame:GetFrame():GetHeight())
		assert.same({ "TOPLEFT", frame:GetFrame(), "TOPLEFT", 0, 0 }, frame:GetRow("ranged"):GetFrame():GetAnchor("TOPLEFT"))
		frame:Apply({ castbar = { enabled = false } })
		assert.equals(1, frame:GetFrame():GetHeight())
		assert.is_false(frame:GetFrame():IsShown())
		frame:Apply({})
		assert.is_true(frame:GetFrame():IsShown())
	end)

	it("keeps sample activity independent of reserved row geometry", function()
		frame:Apply({ mainHand = { enabled = true }, offHand = { enabled = true } })
		local castbar = frame:GetCastbar()
		castbar:Preview({ name = "Sample cast" }, 0.5, "1.0")
		frame:GetRow("mainHand"):SetRange(0, 1)
		frame:GetRow("mainHand"):SetValue(0.25)
		frame:GetRow("offHand"):SetRange(0, 1)
		frame:GetRow("offHand"):SetValue(0.75)
		assert.equals(0.25, frame:GetRow("mainHand"):GetBar():GetStatusBar():GetValue())
		assert.equals(0.75, frame:GetRow("offHand"):GetBar():GetStatusBar():GetValue())
		castbar:Hide()
		assert.equals(48, frame:GetFrame():GetHeight())
		assert.is_true(frame:GetRow("mainHand"):GetFrame():IsShown())
	end)

	it("preserves config and theme inheritance across repeated application", function()
		local config = { mainHand = { enabled = true, height = 14 } }
		local original = ns.Util.Copy(config)
		frame:Apply(config)
		frame:Apply()
		assert.same(original, config)
		assert.equals(40, frame:GetFrame():GetHeight())
		assert.equals(1, #frame:GetRow("mainHand"):GetFrame().__state.points)
		ns.Config:SetThemeValue("fontSize", 15)
		assert.equals(15, frame:GetRow("mainHand").resolved.left.size)
		assert.equals(15, frame:GetCastbar().resolved.name.size)
		assert.same(original, config)
	end)

	it("stops cast presentation on disable and releases owned children", function()
		frame:Apply({ castbar = { gcd = { enabled = true } }, mainHand = { enabled = true } })
		local castbar = frame:GetCastbar()
		castbar:Preview({ name = "Sample cast" }, 0.5, "1.0")
		castbar:PreviewGCD(0.5)
		frame:SetEnabled(false)
		assert.is_false(frame:GetFrame():IsShown())
		assert.is_false(castbar:GetFrame():IsShown())
		assert.is_false(castbar.gcd.bar:IsShown())
		frame:SetEnabled(true)
		castbar:Stop("success")
		frame:Release()
		assert.is_false(castbar.fade:IsPlaying())
		assert.is_true(castbar.released)
		assert.is_true(frame:GetRow("mainHand").released)
		assert.is_false(frame:GetFrame():IsShown())
		assert.has_no_error(function() frame:Release() end)
	end)
end)
