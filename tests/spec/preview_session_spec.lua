local Helpers = require("helpers")
local Mock = Helpers.Mock

describe("Workbench preview sessions", function()
	it("caches plain data, skips static ticks and still observes direct saved-state edits", function()
		local _, wb = Helpers.LoadWorkbench()
		wb:Open("unit.player")
		local values = wb:GetData()
		wb:OnUpdate(0.2)
		assert.equals(values, wb:GetData())
		assert.equals(0, wb.entryState.time)
		wb.state.data.source = "animated"
		wb:OnUpdate(0.2)
		assert.equals("animated", wb:GetData().source)
		assert.equals(0.2, wb.entryState.time)
		wb.dataTarget.set("absorb", 30)
		assert.equals(30, wb:GetData().absorb)
	end)

	it("refreshes saved unit styles and new profiles without retaining released callbacks", function()
		local ns, wb = Helpers.LoadWorkbench()
		wb:Open("unit.player")
		ns.Config:SetUnitValue("player", "width", 310)
		assert.equals(310, wb.handle.parts.uf.resolved.width)
		ns.Config.db:SetProfile("other")
		assert.equals(230, wb.handle.parts.uf.resolved.width)
		local old, session = wb.handle.parts.uf, wb.session
		wb:Select("bar.power")
		assert.is_true(session.released)
		assert.has_no_error(function()
			ns.Config:SetUnitValue("player", "width", 290)
			ns.Config:SetThemeValue("barTexture", "Solid")
		end)
		assert.is_true(old.released)
		assert.equals(230, old.resolved.width)
	end)

	it("finishes cast test actions in static mode and suspends live events while hidden", function()
		local _, wb = Helpers.LoadWorkbench()
		wb:Open("castbar")
		wb:RunAction("start")
		assert.is_true(wb.entryState.casting)
		Mock.time = Mock.time + 10
		wb:OnUpdate(10)
		assert.is_false(wb.entryState.casting)
		wb.dataTarget.set("source", "player")
		wb.window:Hide()
		wb.window:GetFrame():RunScript("OnHide") -- mock visibility does not fire native scripts
		local name = wb.handle.parts.castbar.nameText:GetFrame():GetText()
		Mock.FireEvent("UNIT_SPELLCAST_START", "player")
		assert.equals(name, wb.handle.parts.castbar.nameText:GetFrame():GetText())
		wb.window:Show()
		wb.window:GetFrame():RunScript("OnShow")
		Mock.FireEvent("UNIT_SPELLCAST_START", "player")
		assert.is_true(wb.entryState.casting)
	end)
end)
