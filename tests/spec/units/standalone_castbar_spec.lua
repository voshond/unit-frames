local Helpers = require("helpers")
local Mock = Helpers.Mock

describe("Standalone castbar runtime #castbar", function()
	local ns, timers, store
	before_each(function()
		ns = Helpers.LoadAddon(true, true)
		Mock.InstallUI()
		timers, store = ns.Timers, ns.Config:TimerStore()
	end)

	local function Enable()
		assert.is_true(store:Replace({ enabled = true, mainHand = { enabled = true }, offHand = { enabled = true },
			ranged = { enabled = true }, castbar = { gcd = { enabled = true } } }))
	end

	it("is opt-in and validates settings before creating a runtime frame", function()
		assert.is_nil(timers.component)
		assert.is_false(store:Resolved().enabled)
		assert.is_false(store:Set("width", 1))
		assert.is_nil(ns.Config:GetTimerConfig().width)
		Enable()
		assert.is_not_nil(timers.component)
		assert.equals(timers.component:GetFrame(), ns.EditMode.frames.timers.frame)
		assert.same({ "CENTER", UIParent, "CENTER", 0, -220 }, { timers.component:GetFrame():GetPoint() })
		assert.is_nil(timers.events:GetScript("OnUpdate"))
	end)

	it("routes three native swing types into independent duration bars and text bindings", function()
		Enable()
		Mock.FireEvent("PLAYER_SWING", 2.6, Enum.PlayerSwingType.MainHand)
		Mock.FireEvent("PLAYER_SWING", 1.8, Enum.PlayerSwingType.OffHand)
		Mock.FireEvent("PLAYER_SWING", 2.8, Enum.PlayerSwingType.Ranged)
		for _, key in ipairs({ "mainHand", "offHand", "ranged" }) do
			local swing = timers.feed.swings[key]
			local timer = timers.component:GetRow(key):GetBar():GetStatusBar().__state.timer
			assert.equals(swing.duration, timer.duration)
			assert.equals(Enum.StatusBarTimerDirection.ElapsedTime, timer.direction)
			assert.is_not_nil(swing.binding)
			assert.is_true(swing.ends > Mock.time)
		end
		local offEnd = timers.feed.swings.offHand.ends
		Mock.time = Mock.time + 1
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		assert.equals(Mock.time + 3, timers.feed.swings.mainHand.ends)
		assert.equals(offEnd, timers.feed.swings.offHand.ends)
		Mock.time = Mock.time + 5
		timers.events:RunScript("OnUpdate", 5)
		assert.is_false(timers.feed:HasActiveSwings())
		assert.is_nil(timers.events:GetScript("OnUpdate"))
		assert.equals(0, timers.component:GetRow("mainHand"):GetBar():GetStatusBar():GetValue())
	end)

	it("rejects opaque or invalid timings without leaving a stale swing", function()
		Enable()
		assert.has_error(function() C_DurationUtil.CreateDuration():SetTimeFromStart(GetTime(), Mock.Secret(3)) end)
		for _, seconds in ipairs({ Mock.Secret(3), 0, -1, "bad" }) do
			Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
			assert.has_no_error(function() Mock.FireEvent("PLAYER_SWING", seconds, Enum.PlayerSwingType.MainHand) end)
			assert.is_nil(timers.feed.swings.mainHand.ends)
		end
		assert.has_no_error(function() Mock.FireEvent("PLAYER_SWING", 3, Mock.Secret(0)) end)
		assert.is_false(timers.feed:HasActiveSwings())
	end)

	it("preserves running swings when restyled and clears removed weapons or disabled rows", function()
		Enable()
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		Mock.FireEvent("PLAYER_SWING", 2, Enum.PlayerSwingType.OffHand)
		local ends = timers.feed.swings.mainHand.ends
		store:Set("width", 350)
		ns.Config:SetThemeValue("fontSize", 14)
		assert.equals(ends, timers.feed.swings.mainHand.ends)
		assert.equals(350, timers.component:GetFrame():GetWidth())
		_G.UnitAttackSpeed = function() return 3, nil, nil end
		Mock.FireEvent("UNIT_ATTACK_SPEED", "target")
		assert.is_not_nil(timers.feed.swings.offHand.ends)
		Mock.FireEvent("UNIT_ATTACK_SPEED", "player")
		assert.is_nil(timers.feed.swings.offHand.ends)
		assert.equals(ends, timers.feed.swings.mainHand.ends)
		store:Set("mainHand.enabled", false)
		assert.is_nil(timers.feed.swings.mainHand.ends)
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		assert.is_nil(timers.feed.swings.mainHand.ends)
	end)

	it("resets weapon timers and drops all events and bindings when disabled", function()
		Enable()
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		Mock.FireEvent("WEAPON_SLOT_CHANGED", 16, true)
		assert.is_nil(timers.feed.swings.mainHand.ends)
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		local swing, castbar = timers.feed.swings.mainHand, timers.component:GetCastbar()
		assert.is_not_nil(castbar.timeBinding)
		store:Set("enabled", false)
		assert.same({}, timers.events.__state.events)
		assert.is_nil(timers.events:GetScript("OnUpdate"))
		assert.is_false(timers.component:GetFrame():IsShown())
		assert.same({ "SetEnabled", false }, swing.binding.__calls[#swing.binding.__calls])
		assert.same({ "SetEnabled", false }, castbar.timeBinding.__calls[#castbar.timeBinding.__calls])
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		assert.is_nil(swing.ends)
		store:Set("enabled", true)
		assert.is_true(timers.events.__state.events.PLAYER_SWING)
		assert.is_true(castbar:GetFrame():IsShown())
	end)

	it("subscribes only to enabled sources and tolerates missing swing capabilities", function()
		Enable()
		store:Set("castbar.enabled", false)
		assert.is_nil(timers.events.__state.events.UNIT_SPELLCAST_START)
		assert.is_nil(timers.events.__state.events.SPELL_UPDATE_COOLDOWN)
		assert.is_true(timers.events.__state.events.PLAYER_SWING)
		ns.Caps.swings = false
		timers:Refresh()
		assert.same({}, timers.events.__state.events)
		store:Set("castbar.enabled", true)
		assert.is_true(timers.events.__state.events.UNIT_SPELLCAST_START)
		assert.is_nil(timers.events.__state.events.PLAYER_SWING)
	end)

	it("removes the update script when the last swing row is disabled", function()
		store:Replace({ enabled = true, mainHand = { enabled = true } })
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		assert.is_not_nil(timers.events:GetScript("OnUpdate"))
		store:Set("mainHand.enabled", false)
		assert.is_false(timers.feed:HasActiveSwings())
		assert.is_nil(timers.events:GetScript("OnUpdate"))
		assert.is_nil(timers.events.__state.events.PLAYER_SWING)
	end)

	it("handles player casts, channels and instant-cast global cooldowns", function()
		Enable()
		local castbar = timers.component:GetCastbar()
		_G.UnitCastingInfo = function() return nil end
		_G.UnitChannelInfo = function() return nil end
		Mock.FireEvent("PLAYER_ENTERING_WORLD")
		assert.is_false(castbar:GetFrame():IsShown())
		Mock.FireEvent("UNIT_SPELLCAST_SENT", "player", "target", "guid", 116)
		Mock.cooldowns[116] = { duration = 1.5, onGCD = true }
		Mock.FireEvent("SPELL_UPDATE_COOLDOWN")
		assert.is_true(castbar.gcd.bar:IsShown())
		assert.is_false(castbar:GetFrame():IsShown())
		_G.UnitCastingInfo = function()
			return Mock.Secret("Fireball"), nil, Mock.Secret(135812), 0, 3000, nil, nil, Mock.Secret(false), 133, 77
		end
		Mock.FireEvent("UNIT_SPELLCAST_START", "target", "guid", 133)
		assert.is_false(castbar:GetFrame():IsShown())
		Mock.FireEvent("UNIT_SPELLCAST_START", "player", "guid", 133)
		assert.is_true(castbar:GetFrame():IsShown())
		Mock.FireEvent("UNIT_SPELLCAST_FAILED", "player", "guid", 133, 99)
		assert.is_true(timers.feed.castState.casting)
		Mock.FireEvent("UNIT_SPELLCAST_INTERRUPTED", "player", "guid", 133, nil, 77)
		assert.is_false(timers.feed.castState.casting)
		assert.is_true(castbar.fade:IsPlaying())
		_G.UnitChannelInfo = function()
			return Mock.Secret("Drain Life"), nil, Mock.Secret(136169), 0, 5000, nil, Mock.Secret(false), nil, nil, nil, 88
		end
		Mock.FireEvent("UNIT_SPELLCAST_CHANNEL_START", "player", "guid", 689)
		assert.is_true(timers.feed.castState.channel)
		assert.equals(Enum.StatusBarTimerDirection.RemainingTime, castbar:GetBar():GetStatusBar().__state.timer.direction)
	end)

	it("coordinates Blizzard suppression with the attached player castbar", function()
		local blizzard = Mock.NewObject("StatusBar", nil, "PlayerCastingBarFrame")
		blizzard:RegisterEvent("UNIT_SPELLCAST_START")
		Enable()
		ns.Config:SetUnitValue("player", "castbar.enabled", true)
		ns.oUF.elements.UF_Castbar.enable(ns.Units.frames.player, "player")
		store:Set("enabled", false)
		assert.same({}, blizzard.__state.events)
		ns.Config:SetUnitValue("player", "castbar.enabled", false)
		ns.oUF.elements.UF_Castbar.disable(ns.Units.frames.player)
		assert.is_true(blizzard.__state.events.UNIT_SPELLCAST_START)
		Enable()
		ns.Config:SetUnitValue("player", "castbar.enabled", true)
		ns.oUF.elements.UF_Castbar.enable(ns.Units.frames.player, "player")
		ns.Config:SetUnitValue("player", "castbar.enabled", false)
		ns.oUF.elements.UF_Castbar.disable(ns.Units.frames.player)
		assert.same({}, blizzard.__state.events)
		store:Set("castbar.enabled", false)
		assert.is_true(blizzard.__state.events.UNIT_SPELLCAST_START)
	end)

	it("exports, imports, resets and switches timer profiles without importing positions", function()
		Enable()
		store:Set("width", 330)
		ns.Config:SetPosition(nil, "timers", "CENTER", 19, 23)
		local exported = ns.Profiles:Export("style")
		assert.equals(330, ns.Profiles:Decode(exported).data.timers.width)
		assert.is_true(ns.Profiles:Create("Other"))
		assert.is_false(timers.component:IsEnabled())
		assert.same({}, timers.events.__state.events)
		assert.is_true(ns.Profiles:Import(exported))
		assert.equals(330, timers.component.resolved.width)
		assert.equals(19, ns.Config:GetPosition(nil, "timers").x)
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		assert.is_true(ns.Profiles:Reset())
		assert.is_false(timers.feed:HasActiveSwings())
		assert.is_false(timers.component:IsEnabled())
		assert.equals(19, ns.Config:GetPosition(nil, "timers").x)
	end)
end)

describe("Standalone castbar Edit Mode #castbar", function()
	it("shows a frozen layout in Edit Mode and restores live events on exit", function()
		local ns = Helpers.LoadAddon(true)
		Mock.InstallUI()
		local lem, callbacks, buttons = LibStub:NewLibrary("LibEditMode", 999), {}, {}
		lem.SettingType = { Slider = "slider", Checkbox = "checkbox", Dropdown = "dropdown" }
		lem.frameSelections = {}
		function lem:AddFrame() end
		function lem:AddFrameSettings() end
		function lem:AddFrameSettingsButtons(frame, list) buttons[frame] = list end
		function lem:RegisterCallback(event, callback) callbacks[event] = callback end
		assert(loadfile("UnitFrames/Integration/EditMode.lua"))("UnitFrames", ns)
		assert(loadfile("UnitFrames/Timers/Runtime.lua"))("UnitFrames", ns)
		ns.oUF:RunFactories()
		ns.Config:TimerStore():Replace({ enabled = true, mainHand = { enabled = true } })
		local timers = ns.Timers
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		callbacks.enter()
		assert.is_false(timers.feed:HasActiveSwings())
		assert.same({}, timers.events.__state.events)
		assert.equals(0.25, timers.component:GetRow("mainHand"):GetBar():GetStatusBar():GetValue())
		assert.is_true(timers.component:GetCastbar():GetFrame():IsShown())
		assert.equals("More settings", buttons[timers.component:GetFrame()][1].text)
		callbacks.exit()
		assert.is_true(timers.events.__state.events.PLAYER_SWING)
		assert.equals(0, timers.component:GetRow("mainHand"):GetBar():GetStatusBar():GetValue())
		assert.is_nil(timers.events:GetScript("OnUpdate"))
	end)
end)

describe("Standalone castbar Workbench preview #castbar", function()
	local ns, wb, component, feed
	before_each(function()
		ns, wb = Helpers.LoadWorkbench({ ["X-Build-Channel"] = "release" })
		wb:Open("timers")
		wb.styleTarget.set("mainHand.enabled", true)
		wb.styleTarget.set("offHand.enabled", true)
		component, feed = wb.handle.parts.timers, wb.handle.feed
	end)

	it("edits persistent settings while displaying samples with the feature disabled", function()
		assert.is_nil(ns.Timers.component)
		assert.is_false(wb.styleTarget.resolved().enabled)
		assert.is_true(component:GetFrame():IsShown())
		assert.equals(0.25, component:GetRow("mainHand"):GetBar():GetStatusBar():GetValue())
		assert.equals(0.7, component:GetRow("offHand"):GetBar():GetStatusBar():GetValue())
		wb.styleTarget.set("enabled", true)
		wb.styleTarget.set("width", 310)
		assert.equals(310, ns.Timers.component.resolved.width)
		assert.equals(310, component.resolved.width)
		assert.is_false(ns.Timers.feed:HasActiveSwings())
		assert.is_false(component:GetRow("ranged"):IsEnabled())
	end)

	it("animates independent swing rows and channels then restores frozen samples", function()
		wb.dataTarget.set("spell", 4)
		wb.dataTarget.set("source", "animated")
		wb:OnUpdate(0.5)
		local main = component:GetRow("mainHand"):GetBar():GetStatusBar():GetValue()
		local off = component:GetRow("offHand"):GetBar():GetStatusBar():GetValue()
		assert.is_true(main ~= off)
		assert.equals("Arcane Missiles", component:GetCastbar().nameText:GetFrame():GetText())
		wb.dataTarget.set("source", "static")
		assert.equals(0.25, component:GetRow("mainHand"):GetBar():GetStatusBar():GetValue())
		assert.same({}, wb.eventFrame.__state.events)
	end)

	it("shares the live feed and tears it down on source changes, hide and release", function()
		wb.dataTarget.set("source", "player")
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		assert.is_not_nil(feed.swings.mainHand.ends)
		wb.dataTarget.set("source", "static")
		assert.is_false(feed:HasActiveSwings())
		assert.same({}, wb.eventFrame.__state.events)
		wb.dataTarget.set("source", "player")
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		wb.window:Hide()
		wb.window:GetFrame():RunScript("OnHide")
		assert.is_false(feed:HasActiveSwings())
		assert.same({}, wb.eventFrame.__state.events)
		ns.Config:SetThemeValue("fontSize", 14)
		local timeBinding = component:GetCastbar().timeBinding
		assert.same({ "SetEnabled", false }, timeBinding.__calls[#timeBinding.__calls])
		wb.window:Show()
		wb.window:GetFrame():RunScript("OnShow")
		Mock.FireEvent("PLAYER_SWING", 3, Enum.PlayerSwingType.MainHand)
		assert.is_not_nil(feed.swings.mainHand.ends)
		wb:Select("unit.player")
		assert.is_true(component.released)
		assert.is_false(feed:HasActiveSwings())
		local binding = feed.swings.mainHand.binding
		assert.same({ "SetEnabled", false }, binding.__calls[#binding.__calls])
		assert.has_no_error(function() ns.Config:SetThemeValue("fontSize", 13) end)
	end)

	it("restores frozen samples when a hidden preview is reopened", function()
		wb.window:Hide()
		wb.window:GetFrame():RunScript("OnHide")
		ns.Config:SetThemeValue("fontSize", 14)
		assert.equals(0, component:GetRow("mainHand"):GetBar():GetStatusBar():GetValue())
		wb.window:Show()
		wb.window:GetFrame():RunScript("OnShow")
		assert.equals(0.25, component:GetRow("mainHand"):GetBar():GetStatusBar():GetValue())
		assert.same({}, wb.eventFrame.__state.events)
	end)
end)
